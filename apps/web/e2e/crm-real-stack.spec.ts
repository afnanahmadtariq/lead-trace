import { expect, test } from '@playwright/test'

test('real CRM persists contacts, notes, deals, follow-ups, imports and research links', async ({ page, request }) => {
  test.skip(process.env.E2E_USE_REAL_STACK !== 'true', 'Requires the real API and an isolated PostgreSQL database')
  const api = `http://127.0.0.1:${process.env.E2E_API_PORT || 3001}`
  const seed = await request.post(`${api}/e2e/seed`, { headers: { 'x-e2e-secret': process.env.E2E_SEED_SECRET || 'e2e-local-secret-ok' } })
  expect(seed.ok()).toBeTruthy()
  const credentials = await seed.json()
  await page.goto('/sign-in')
  await page.getByLabel('Work email').fill(credentials.email)
  await page.getByLabel('Password').fill(credentials.password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.waitForURL(/\/(?:dashboard|onboarding)(?:[/?#]|$)/)
  if (new URL(page.url()).pathname === '/onboarding') {
    await page.getByRole('button', { name: /E2E Workspace/ }).click()
    await page.waitForURL('**/dashboard')
  }
  await page.getByRole('link', { name: 'Contacts', exact: true }).click()
  await page.getByRole('button', { name: 'Add contact', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Add contact' })
  await dialog.getByLabel('Full name').fill('CRM Real Tester')
  await dialog.getByLabel('Email', { exact: true }).fill('real-crm@example.test')
  await dialog.getByLabel('Company', { exact: true }).fill('Northstar')
  await dialog.getByLabel('Owner').selectOption({ label: 'E2E Tester' })
  await dialog.getByRole('button', { name: 'Create contact' }).click()
  await expect(page).toHaveURL(/\/dashboard\/contacts\/[^/]+$/)
  const contactUrl = page.url(), contactId = contactUrl.split('/').pop()
  await page.getByRole('button', { name: 'Add note', exact: true }).click()
  await page.getByLabel('Conversation note').fill('Persist this conversation note in PostgreSQL.')
  await page.getByRole('dialog').getByRole('button', { name: 'Add note', exact: true }).click()
  await expect(page.getByText('Persist this conversation note in PostgreSQL.', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('Persist this conversation note in PostgreSQL.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Add follow-up', exact: true }).click()
  await page.getByLabel('Next action').fill('Verify real follow-up')
  await page.getByLabel('Due date and time (your local time)').fill('2027-01-05T10:00')
  await page.getByRole('dialog').getByRole('button', { name: 'Add follow-up', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Complete Verify real follow-up' })).toBeVisible()
  await page.getByRole('checkbox', { name: 'Complete Verify real follow-up' }).check()
  await page.getByText('Completed · 1', { exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Complete Verify real follow-up' })).toBeChecked()
  await page.reload()
  await page.getByText('Completed · 1', { exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Complete Verify real follow-up' })).toBeChecked()
  await page.getByRole('button', { name: 'Add deal', exact: true }).click()
  await page.getByLabel('Deal name').fill('Real database deal')
  await page.getByLabel('Value', { exact: true }).fill('1234.56')
  await page.getByRole('button', { name: 'Create deal' }).click()
  await expect(page.getByRole('link', { name: 'Real database deal' })).toBeVisible()
  await page.goto('/dashboard/pipeline')
  await page.getByRole('button', { name: 'Edit deal' }).click()
  await page.getByRole('dialog').getByLabel('Stage').selectOption('won')
  await page.getByRole('button', { name: 'Save deal' }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.reload()
  await expect(page.locator('section').filter({ has: page.getByRole('heading', { name: /^Won/ }) }).getByRole('heading', { name: 'Real database deal' })).toBeVisible()
  await page.goto(contactUrl)
  await page.getByRole('button', { name: 'Edit contact' }).click()
  await page.getByRole('dialog').getByLabel('Lifecycle').selectOption('customer')
  await page.getByRole('dialog').getByLabel('Job title').fill('Head of sales')
  await page.getByRole('button', { name: 'Save contact', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.reload()
  await expect(page.getByRole('banner').getByText('Customer · Head of sales · Northstar', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Research contact', exact: true }).click()
  await expect(page.getByLabel('Prospect name')).toHaveValue('CRM Real Tester')
  // Queue research through the real HTTP API, without calling paid discovery from this deterministic test.
  const queued = await page.request.post(`${api}/research-runs`, { data: { prospectId: contactId, prospectName: 'CRM Real Tester', offerName: 'Lead Trace', offerContext: 'Evidence-backed prospect research and a built-in sales CRM.', goal: 'meeting' } })
  expect(queued.ok()).toBeTruthy()
  expect((await queued.json()).prospectId).toBe(contactId)
  await page.goto(contactUrl)
  await expect(page.getByRole('link', { name: /Meeting research/ })).toBeVisible()
  await page.goto('/dashboard/contacts')
  await page.getByRole('button', { name: 'Import CSV' }).click()
  await page.getByLabel('Or paste CSV').fill('name,email,company\nDuplicate,REAL-CRM@example.test,Northstar\nImported Person,imported@example.test,Southstar')
  await page.getByRole('button', { name: 'Import contacts', exact: true }).click()
  await expect(page.getByText('1 contacts imported; 1 email matches skipped.', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('link', { name: 'Imported Person', exact: true })).toBeVisible()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export CSV' }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toBe('lead-trace-contacts.csv')
  await page.goto('/dashboard/integrations')
  const statusResponse = await page.request.get(`${api}/crm/calendar`)
  const status = await statusResponse.json()
  expect(status.connected).toBe(false)
  if (!status.configured) await expect(page.getByRole('button', { name: 'Connect Google Calendar' })).toBeDisabled()
  await page.goto('/dashboard/contacts/missing-contact')
  await expect(page.getByRole('heading', { name: "This page isn't here." })).toBeVisible()
})
