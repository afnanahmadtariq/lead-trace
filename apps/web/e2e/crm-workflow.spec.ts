import { expect, test } from '@playwright/test'
import { e2eFixtures } from './fixtures.mjs'

const apiURL = `http://127.0.0.1:${process.env.E2E_API_PORT || 3001}`
const webURL = `http://127.0.0.1:${process.env.E2E_WEB_PORT || 3000}`

test('CRM gives a next step without Calendar and creates records from their own pages', async ({ page, request }) => {
  test.skip(process.env.E2E_USE_REAL_STACK === 'true', 'Uses isolated CRM UI fixtures')
  const response = await request.post(`${apiURL}/api/auth/sign-in/email`, { data: { email: e2eFixtures.user.email, password: e2eFixtures.user.password } })
  expect(response.ok()).toBeTruthy()
  const { token } = await response.json()
  await page.context().addCookies([webURL, apiURL].map((url) => ({ name: 'lead-trace.session_token', value: token, url, httpOnly: true, sameSite: 'Lax' as const })))
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('console', (message) => {
    if (message.type() === 'error' && /hydrat|server rendered/i.test(message.text())) errors.push(message.text())
  })
  await page.request.delete(`${apiURL}/crm/calendar`)

  await page.goto('/dashboard')
  await expect(page.getByRole('heading', { name: 'Make your next move.' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Your next follow-ups' })).toBeVisible()
  await page.getByRole('link', { name: 'Add contact', exact: true }).click()
  const contactDialog = page.getByRole('dialog', { name: 'Add contact' })
  await expect(contactDialog.getByLabel('Full name')).toBeFocused()
  await contactDialog.getByLabel('Full name').fill('Nora Workflow')
  await contactDialog.getByLabel('Email', { exact: true }).fill('nora@workflow.test')
  await contactDialog.getByLabel('Company', { exact: true }).fill('Workflow Labs')
  await contactDialog.getByRole('button', { name: 'Create contact' }).click()
  await expect(page.getByRole('heading', { name: 'Nora Workflow', exact: true })).toBeVisible()
  const contactUrl = page.url()
  await expect(page.getByRole('region', { name: 'Next step' })).toContainText('Give this relationship a next step')

  await page.getByRole('button', { name: 'Schedule meeting', exact: true }).click()
  await page.getByRole('button', { name: 'Plan a follow-up instead' }).click()
  const followUp = page.getByRole('dialog', { name: 'Add follow-up' })
  await followUp.getByLabel('Next action').fill('Discuss Nora’s proposal')
  await followUp.getByLabel('Due date and time (your local time)').fill('2099-01-02T10:00')
  await followUp.getByRole('button', { name: 'Add follow-up', exact: true }).click()
  await expect(followUp).not.toBeVisible()
  await expect(page.getByRole('region', { name: 'Next step' })).toContainText('Discuss Nora’s proposal')

  await page.goto('/dashboard/tasks')
  await page.getByRole('button', { name: 'Add follow-up', exact: true }).click()
  await page.getByLabel('Choose a contact').fill('Nora Workflow')
  await page.getByRole('button', { name: /Nora Workflow/ }).click()
  await page.getByLabel('Next action').fill('Recover overdue promise')
  await page.getByLabel('Due date and time (your local time)').fill('2020-01-01T10:00')
  await page.getByRole('dialog').getByRole('button', { name: 'Add follow-up', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByRole('button', { name: /^Overdue/ }).click()
  await expect(page.getByRole('checkbox', { name: 'Complete Recover overdue promise' })).toBeVisible()
  await expect(page.getByRole('checkbox', { name: 'Complete Discuss Nora’s proposal' })).not.toBeVisible()
  await page.getByRole('checkbox', { name: 'Complete Recover overdue promise' }).check()
  await expect(page.getByRole('checkbox', { name: 'Complete Recover overdue promise' })).not.toBeVisible()
  await page.locator('summary').filter({ hasText: /^Completed/ }).click()
  await page.getByRole('checkbox', { name: 'Complete Recover overdue promise' }).uncheck()
  await expect(page.getByRole('checkbox', { name: 'Complete Recover overdue promise' })).toBeVisible()

  await page.goto('/dashboard/pipeline')
  await page.getByRole('button', { name: 'Add deal', exact: true }).click()
  await page.getByLabel('Choose a contact').fill('Nora Workflow')
  await page.getByRole('button', { name: /Nora Workflow/ }).click()
  await page.getByLabel('Deal name').fill('Workflow Labs annual plan')
  await page.getByLabel('Value', { exact: true }).fill('3500')
  await page.getByRole('dialog').getByRole('combobox', { name: 'Stage', exact: true }).selectOption('qualified')
  await page.getByRole('button', { name: 'Create deal' }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByLabel('Show stage').selectOption('qualified')
  await expect(page.getByRole('heading', { name: 'Workflow Labs annual plan' })).toBeVisible()
  await page.getByLabel('Show stage').selectOption('won')
  await expect(page.getByRole('heading', { name: 'Workflow Labs annual plan' })).not.toBeVisible()
  await page.getByLabel('Show stage').selectOption('all')
  await page.getByRole('button', { name: 'Table view', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Table view', exact: true })).toHaveAttribute('aria-pressed', 'true')
  const table = page.getByRole('region', { name: 'Deals table' })
  await expect(table.getByRole('row', { name: /Workflow Labs annual plan/ })).toContainText('$3,500.00')
  await page.getByLabel('Show stage').selectOption('won')
  await expect(table).toContainText('No deals in this view.')
  await page.getByRole('button', { name: 'Board view', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Workflow Labs annual plan' })).not.toBeVisible()
  await page.getByLabel('Show stage').selectOption('qualified')
  await page.getByRole('button', { name: 'Table view', exact: true }).click()
  await table.getByRole('button', { name: 'Edit deal: Workflow Labs annual plan', exact: true }).click()
  await page.getByRole('dialog').getByRole('combobox', { name: 'Stage', exact: true }).selectOption('proposal')
  await page.getByRole('button', { name: 'Save deal', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(table).toContainText('No deals in this view.')
  await page.getByLabel('Show stage').selectOption('proposal')
  await expect(table.getByRole('row', { name: /Workflow Labs annual plan/ })).toContainText('Proposal')
  await page.reload()
  await expect(page.getByRole('button', { name: 'Table view', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(table.getByRole('link', { name: 'Nora Workflow', exact: true })).toHaveAttribute('href', new URL(contactUrl).pathname)
  if (process.env.CRM_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.CRM_SCREENSHOT_DIR}/pipeline-table.png`, fullPage: true, animations: 'disabled', caret: 'initial' })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  if (process.env.CRM_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.CRM_SCREENSHOT_DIR}/pipeline-table-mobile.png`, fullPage: true, animations: 'disabled', caret: 'initial' })
  await page.setViewportSize({ width: 1280, height: 720 })
  await page.getByRole('button', { name: 'Board view', exact: true }).click()
  if (process.env.CRM_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.CRM_SCREENSHOT_DIR}/pipeline-workflow.png`, fullPage: true, animations: 'disabled', caret: 'initial' })

  await page.goto(contactUrl)
  await page.getByRole('button', { name: 'Add note', exact: true }).click()
  await page.getByLabel('Conversation note').fill('Temporary note to delete')
  await page.getByRole('dialog').getByRole('button', { name: 'Add note', exact: true }).click()
  await expect(page.getByText('Temporary note to delete')).toBeVisible()
  await page.getByRole('button', { name: 'Delete note' }).click()
  await page.getByRole('dialog', { name: 'Delete note?' }).getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(page.getByText('Temporary note to delete')).not.toBeVisible()
  await page.getByRole('button', { name: 'Delete follow-up: Discuss Nora’s proposal' }).click()
  await page.getByRole('dialog', { name: 'Delete follow-up?' }).getByRole('button', { name: 'Cancel' }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByRole('link', { name: 'Research contact', exact: true }).click()
  await expect(page.getByLabel('Prospect name')).toHaveValue('Nora Workflow')
  await expect(page.getByLabel('Prospect name')).toHaveAttribute('readonly')
  await page.goto(contactUrl)
  if (process.env.CRM_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.CRM_SCREENSHOT_DIR}/contact-workflow.png`, fullPage: true, animations: 'disabled', caret: 'initial' })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('link', { name: 'Contacts', exact: true })).toContainText('Contacts')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  if (process.env.CRM_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.CRM_SCREENSHOT_DIR}/contact-workflow-mobile.png`, fullPage: true, animations: 'disabled', caret: 'initial' })
  await page.goto('/dashboard/pipeline')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.goto('/dashboard/contacts?q=no-such-person')
  await expect(page.getByRole('heading', { name: 'No matching contacts' })).toBeVisible()
  await page.getByRole('link', { name: 'Clear search' }).click()
  await expect(page.getByRole('link', { name: 'Nora Workflow', exact: true })).toBeVisible()
  await page.goto('/dashboard')
  await expect(page.getByRole('heading', { name: 'Your next follow-ups' })).toBeVisible()
  if (process.env.CRM_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.CRM_SCREENSHOT_DIR}/home-workflow-mobile.png`, fullPage: true, animations: 'disabled', caret: 'initial' })
  expect(errors).toEqual([])
})
