import { expect, test } from '@playwright/test'

test('real lead shortlist qualifies, saves to CRM, and preserves its evidence', async ({ page, request }) => {
  test.skip(process.env.E2E_USE_REAL_STACK !== 'true', 'Requires the real API and PostgreSQL; discovery fixtures avoid provider charges')
  const api = `http://127.0.0.1:${process.env.E2E_API_PORT || 3001}`
  const seedResponse = await request.post(`${api}/e2e/seed`, { headers: { 'x-e2e-secret': process.env.E2E_SEED_SECRET || 'e2e-local-secret-ok' } })
  expect(seedResponse.ok()).toBeTruthy()
  const seed = await seedResponse.json()
  await page.goto('/sign-in')
  await page.getByLabel('Work email').fill(seed.email)
  await page.getByLabel('Password').fill(seed.password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.waitForURL(/\/(?:dashboard|onboarding)(?:[/?#]|$)/)
  if (new URL(page.url()).pathname === '/onboarding') {
    await page.getByRole('button', { name: /E2E Workspace/ }).click()
    await page.waitForURL('**/dashboard')
  }
  await page.getByRole('link', { name: 'Find leads', exact: true }).click()
  await page.getByRole('link', { name: /Seeded SaaS buyers/ }).click()
  await expect(page.getByRole('heading', { name: 'Maya Chen', exact: true })).toBeVisible()
  await expect(page.getByText('Source-supported match · 3/3 criteria', { exact: true })).toBeVisible()
  await page.getByText('Why this person matches', { exact: true }).click()
  await expect(page.getByText('Northstar leadership', { exact: true }).first()).toBeVisible()
  await expect(page.getByRole('link', { name: 'Northstar leadership' }).first()).toHaveAttribute('href', 'https://northstar.example.com/team')
  await page.getByRole('button', { name: 'Dismiss', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Restore', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Restore', exact: true }).click()
  await page.getByRole('button', { name: 'Qualify lead', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Save to CRM', exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: 'Save to CRM', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Review and save to CRM' })
  await expect(dialog.getByLabel('Full name')).toHaveValue('Maya Chen')
  await dialog.getByLabel('Email (if independently known)').fill('maya@example.test')
  await dialog.getByLabel('Owner').selectOption({ label: 'E2E Tester' })
  await dialog.getByRole('button', { name: 'Save reviewed lead' }).click()
  await expect(page).toHaveURL(/\/dashboard\/contacts\/[^/]+$/)
  const contactUrl = page.url()
  await expect(page.getByRole('heading', { name: 'Maya Chen', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Lead discovery', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Seeded SaaS buyers', exact: true })).toBeVisible()
  await expect(page.getByText('Maya Chen is Head of Sales at Northstar, a SaaS company in London.', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('link', { name: 'Seeded SaaS buyers', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Seeded SaaS buyers', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Open CRM contact', exact: true })).toHaveAttribute('href', new URL(contactUrl).pathname)
  await page.getByRole('button', { name: /^Saved to CRM/ }).click()
  await expect(page.getByRole('heading', { name: 'Maya Chen', exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  if (process.env.LEAD_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.LEAD_SCREENSHOT_DIR}/shortlist-mobile.png`, fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  if (process.env.LEAD_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.LEAD_SCREENSHOT_DIR}/shortlist.png`, fullPage: true })
})

test('live browser creates a lead search and saves an actual discovered lead to CRM', async ({ page, request }) => {
  test.skip(process.env.E2E_USE_REAL_STACK !== 'true' || process.env.LIVE_PROVIDER_TESTS !== 'true', 'Opt-in real API and live provider check')
  test.setTimeout(120000)
  const api = `http://127.0.0.1:${process.env.E2E_API_PORT || 3001}`
  const response = await request.post(`${api}/e2e/seed`, { headers: { 'x-e2e-secret': process.env.E2E_SEED_SECRET || 'e2e-local-secret-ok' } })
  expect(response.ok()).toBeTruthy()
  const seed = await response.json()
  await page.goto('/sign-in')
  await page.getByLabel('Work email').fill(seed.email)
  await page.getByLabel('Password').fill(seed.password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.waitForURL(/\/(?:dashboard|onboarding)(?:[/?#]|$)/)
  if (new URL(page.url()).pathname === '/onboarding') {
    await page.getByRole('button', { name: /E2E Workspace/ }).click()
    await page.waitForURL('**/dashboard')
  }
  await page.goto('/dashboard/leads')
  await page.getByLabel('Search name').fill('Live Austin agency founders')
  await page.getByLabel('Industry or market').fill('digital marketing agency')
  await page.getByLabel('Buyer role').fill('Founder')
  await page.getByLabel('Location (optional)').fill('Austin')
  await page.getByRole('button', { name: 'Find leads', exact: true }).click()
  await expect(page).toHaveURL(/\/dashboard\/leads\/[^/]+$/)
  const searchUrl = page.url()
  await expect(page.getByRole('button', { name: 'Qualify lead', exact: true }).first()).toBeVisible({ timeout: 80000 })
  await expect(page.getByRole('button', { name: /^Source-supported matches/ })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByText('Source-supported match · 3/3 criteria', { exact: true }).first()).toBeVisible()
  await page.getByRole('button', { name: 'Qualify lead', exact: true }).first().click()
  await page.getByRole('button', { name: 'Save to CRM', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Review and save to CRM' })
  const name = await dialog.getByLabel('Full name').inputValue()
  await dialog.getByRole('button', { name: 'Save reviewed lead' }).click()
  await expect(page).toHaveURL(/\/dashboard\/contacts\/[^/]+$/)
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Live Austin agency founders', exact: true })).toHaveAttribute('href', new URL(searchUrl).pathname)
  await expect(page.getByRole('link', { name: 'Research contact', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Lead discovery', exact: true })).toBeVisible()
})
