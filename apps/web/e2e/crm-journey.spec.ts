import { expect, test } from '@playwright/test'
import { e2eFixtures } from './fixtures.mjs'

const apiURL = `http://127.0.0.1:${process.env.E2E_API_PORT || 3001}`
const webURL = `http://127.0.0.1:${process.env.E2E_WEB_PORT || 3000}`

test('contact to deal, follow-up, research and Calendar meeting', async ({ page, request }) => {
  test.skip(process.env.E2E_USE_REAL_STACK === 'true', 'UI provider fixtures; real service behavior is covered by CRM integration tests')
  const signIn = await request.post(`${apiURL}/api/auth/sign-in/email`, { data: { email: e2eFixtures.user.email, password: e2eFixtures.user.password } })
  expect(signIn.ok()).toBeTruthy()
  const { token } = await signIn.json()
  await page.context().addCookies([webURL, apiURL].map((url) => ({ name: 'lead-trace.session_token', value: token, url, httpOnly: true, sameSite: 'Lax' as const })))
  await page.goto('/dashboard/contacts')
  await page.getByRole('button', { name: 'Add contact', exact: true }).click()
  const modal = page.getByRole('dialog', { name: 'Add contact' })
  await modal.getByLabel('Full name').fill('Maya Chen')
  await modal.getByLabel('Email', { exact: true }).fill('maya@crm.test')
  await modal.getByLabel('Company', { exact: true }).fill('Northstar')
  await modal.getByLabel('Company domain').fill('northstar.test')
  await modal.getByLabel('Owner').selectOption('e2e-user-id')
  await modal.getByRole('button', { name: 'Create contact' }).click()
  await expect(page).toHaveURL(/\/dashboard\/contacts\/[^/]+$/)
  const contactUrl = page.url()
  await expect(page.getByRole('heading', { name: 'Maya Chen' })).toBeVisible()
  await page.getByRole('button', { name: 'Add note', exact: true }).click()
  await page.getByLabel('Conversation note').fill('Pilot agreed. Send a proposal before the next meeting.')
  await page.getByRole('dialog').getByRole('button', { name: 'Add note', exact: true }).click()
  await expect(page.getByText('Pilot agreed. Send a proposal before the next meeting.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Add follow-up', exact: true }).click()
  await page.getByLabel('Next action').fill('Send pilot proposal')
  await page.getByLabel('Due date and time (your local time)').fill('2027-01-02T10:00')
  await page.getByRole('dialog').getByRole('button', { name: 'Add follow-up', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Send pilot proposal', level: 3 })).toBeVisible()
  await page.getByRole('checkbox', { name: 'Complete Send pilot proposal' }).check()
  await page.getByText('Completed · 1', { exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Complete Send pilot proposal' })).toBeChecked()
  await page.getByText('Add deal', { exact: true }).click()
  await page.getByLabel('Deal name').fill('Northstar pilot')
  await page.getByLabel('Value', { exact: true }).fill('2400')
  await page.getByRole('button', { name: 'Create deal' }).click()
  await expect(page.getByRole('link', { name: 'Northstar pilot' })).toBeVisible()
  await page.goto('/dashboard/pipeline')
  await page.getByRole('button', { name: 'Edit deal' }).click()
  await page.getByRole('dialog').getByLabel('Stage').selectOption('proposal')
  await page.getByRole('button', { name: 'Save deal' }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(page.locator('section').filter({ has: page.getByRole('heading', { name: /^Proposal/ }) }).getByRole('heading', { name: 'Northstar pilot' })).toBeVisible()
  if (process.env.CRM_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.CRM_SCREENSHOT_DIR}/pipeline.png`, fullPage: true, animations: 'disabled', caret: 'initial' })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto('/dashboard/integrations')
  await page.getByRole('button', { name: 'Connect Google Calendar' }).click()
  await expect(page.getByText('Your Calendar is connected.', { exact: true })).toBeVisible()
  await page.goto(contactUrl)
  await page.getByRole('button', { name: 'Schedule meeting', exact: true }).click()
  await page.getByLabel('Meeting title').fill('Northstar pilot discovery')
  await page.getByLabel('Starts (your local time)').fill('2027-01-03T10:00')
  await page.getByLabel('Ends (your local time)').fill('2027-01-03T09:30')
  await page.getByRole('dialog').getByRole('button', { name: 'Schedule meeting', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('Choose an end time after the meeting starts.')
  await expect(page.getByLabel('Meeting title')).toHaveValue('Northstar pilot discovery')
  await page.getByLabel('Ends (your local time)').fill('2027-01-03T10:30')
  await expect(page.getByRole('checkbox', { name: /Email a calendar invitation/ })).not.toBeChecked()
  await page.getByRole('dialog').getByRole('button', { name: 'Schedule meeting', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Northstar pilot discovery' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Open in Google Calendar' })).toHaveAttribute('href', /google.com\/calendar/)
  if (process.env.CRM_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.CRM_SCREENSHOT_DIR}/contact.png`, fullPage: true, animations: 'disabled', caret: 'initial' })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  if (process.env.CRM_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.CRM_SCREENSHOT_DIR}/contact-mobile.png`, fullPage: true, animations: 'disabled', caret: 'initial' })
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.getByRole('link', { name: 'Research contact', exact: true }).click()
  await expect(page.getByLabel('Prospect name')).toHaveValue('Maya Chen')
  await expect(page.getByLabel('Prospect name')).toHaveAttribute('readonly')
  await page.getByLabel('Offer', { exact: true }).fill('Lead Trace')
  await page.getByLabel('Problem you solve and outcome you create').fill('A research and CRM workflow for sales teams preparing for better conversations.')
  const researchResponse = page.waitForResponse((response) => response.url() === `${apiURL}/research-runs` && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Build meeting brief' }).click()
  const created = await (await researchResponse).json()
  expect(created.prospect.id).toBe(contactUrl.split('/').pop())
  await page.goto('/dashboard/contacts')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export CSV' }).click()
  expect((await download).suggestedFilename()).toBe('lead-trace-contacts.csv')
  await page.getByRole('button', { name: 'Import CSV' }).click()
  await page.getByLabel('Or paste CSV').fill('name,email,company\nMaya Chen,maya@crm.test,Northstar\nAlex River,alex@crm.test,Southstar')
  await page.getByRole('button', { name: 'Import contacts', exact: true }).click()
  await expect(page.getByText('1 contacts imported; 1 email matches skipped.', { exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Alex River', exact: true })).toBeVisible()
  await page.goto('/dashboard/tasks')
  await page.getByText('Completed · 1', { exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Complete Send pilot proposal' })).toBeChecked()
})
